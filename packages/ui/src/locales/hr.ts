// verbs agree with the subject's gender, so a named subject uses the "-o/la"
// dual ending ("je reagirao/la"), and 2nd-person past tense is avoided in
// favour of imperatives, present tense or impersonal phrasing ("Ovdje još nema
// tvojih objava.", "Ova je osoba blokirana.").
